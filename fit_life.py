# Проект FitLife - MVP версия 1.0

# константы для расчета нормы воды
WATER_PER_KG = 30
ML_IN_LITER = 1000


# 0. ПРИВЕТСТВИЕ
print('Приветствую! Я ваш личный помощник в ведении здорового образа жизни.')
print('Давайте определим вашу дневную норму воды.')

# 1. ЗНАКОМСТВО
user_name = input('Введите ваше имя: ')
user_name = user_name.title()
user_age = int(input('Введите ваш возраст: '))


# 2. СБОР ДАННЫХ
# проверка, что если вес дробное число, то вводится не через точку
# спрашиваем до тех пор, пока не введет в нужном формате
while True:
    try:
        user_weight = float(input('Введите ваш вес в килограммах: '))
        break
    except ValueError:
        print('Замените запятую на точку, пожалуйста.')


# проверка, что рост вводится не через запятую
# спрашиваем до тех пор, пока не введет в нужном формате
while True:
    try:
        user_height = float(input('Введите ваш рост в метрах (напр, 1.68): '))
        break
    except ValueError:
        print('Нет, не так. Введите через точку (например, 1.68)')


# 3. РАССЧЕТ bmi (ИМТ)
bmi = user_weight / (user_height ** 2)
bmi = round(bmi, 1)


# 4. РАССЧЕТ НОРМЫ ВОДЫ В МЛ --> Л
water_ml = user_weight * WATER_PER_KG
water_l = water_ml / ML_IN_LITER


# 5. ВЫВОД ОТЧЕТА ДЛЯ ПОЛЬЗОВАТЕЛЯ
print(f'''{user_name}, я всё посчитал! Вам ({user_age} лет),\n
Ваш ИМТ (индекс массы тела) составляет: {bmi}
Старайтесь пить примерно {water_l:.1f} л воды в день\n''')
print("Расчет окончен. Будьте здоровы!")
